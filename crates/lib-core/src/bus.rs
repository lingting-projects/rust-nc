//! 进程内通知总线。
//!
//! 业务层写库后通过 [`notify`] 发布数据更新事件，界面侧订阅后自行读取最新数据。
//! 总线实例全进程唯一，因此发布方与订阅方不需要互相持有引用：
//! 事件类型定义在 `types-core`，发布方只依赖本模块。
//!
//! 事件不携带数据，订阅方收到后必须重新读取；同一订阅的多次通知会被合并，
//! 因此处理逻辑必须幂等。

use std::sync::LazyLock;

use framework_bus::Bus;

/// 全局唯一的总线实例。
///
/// 默认使用同步分发者：订阅方只做唤醒，处理函数在哪里执行由安装方决定。
static BUS: LazyLock<Bus> = LazyLock::new(Bus::new);

/// 取全局总线。
///
/// 界面在启动阶段拿到它，装上自己的分发者并放进全局状态；
/// 业务层直接用 [`notify`] 发布事件。
pub fn bus() -> &'static Bus {
    &BUS
}

/// 发布 `E` 类事件。
///
/// 任意线程可调用，不会阻塞也不会失败；没有订阅者时静默返回。
pub fn notify<E: 'static>() {
    BUS.notify::<E>();
}
